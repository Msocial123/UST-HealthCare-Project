import uuid
from typing import Annotated

from fastapi import APIRouter, Depends, Query, status

from app.api.deps import DbSession, require_permission
from app.core.tokens import Principal
from app.domain.roles import Permission
from app.schemas.common import ErrorResponse, Page
from app.schemas.patient import PatientCreate, PatientRead, PatientSummary, PatientUpdate
from app.services.patient_service import PatientService

router = APIRouter(
    prefix="/patients",
    tags=["patients"],
    responses={401: {"model": ErrorResponse}, 403: {"model": ErrorResponse}},
)

PatientReader = Annotated[Principal, Depends(require_permission(Permission.PATIENTS_READ))]
PatientWriter = Annotated[Principal, Depends(require_permission(Permission.PATIENTS_WRITE))]
PatientDeactivator = Annotated[Principal, Depends(require_permission(Permission.PATIENTS_DEACTIVATE))]


@router.post(
    "",
    response_model=PatientRead,
    status_code=status.HTTP_201_CREATED,
    summary="Register a patient (the medical record number is generated by the server)",
    responses={409: {"model": ErrorResponse}},
)
def register_patient(body: PatientCreate, db: DbSession, actor: PatientWriter) -> PatientRead:
    return PatientRead.model_validate(PatientService(db).register_patient(body, actor=actor))


@router.get("", response_model=Page[PatientSummary], summary="Search patients (paginated)")
def search_patients(
    db: DbSession,
    _: PatientReader,
    search: Annotated[
        str | None,
        Query(
            min_length=1,
            max_length=100,
            description=(
                "Whitespace-separated terms; every term must match a first/last name prefix "
                "(case-insensitive), an exact MRN or an exact date of birth (YYYY-MM-DD)."
            ),
        ),
    ] = None,
    limit: Annotated[int, Query(ge=1, le=100)] = 20,
    offset: Annotated[int, Query(ge=0)] = 0,
    is_active: Annotated[bool | None, Query(description="Filter by active status")] = None,
) -> Page[PatientSummary]:
    return PatientService(db).search_patients(search=search, limit=limit, offset=offset, is_active=is_active)


@router.get(
    "/{patient_id}",
    response_model=PatientRead,
    summary="Get a patient",
    responses={404: {"model": ErrorResponse}},
)
def get_patient(patient_id: uuid.UUID, db: DbSession, _: PatientReader) -> PatientRead:
    return PatientRead.model_validate(PatientService(db).get_patient(patient_id))


@router.patch(
    "/{patient_id}",
    response_model=PatientRead,
    summary="Update patient demographics",
    responses={404: {"model": ErrorResponse}, 409: {"model": ErrorResponse}},
)
def update_patient(
    patient_id: uuid.UUID, body: PatientUpdate, db: DbSession, actor: PatientWriter
) -> PatientRead:
    return PatientRead.model_validate(PatientService(db).update_patient(patient_id, body, actor=actor))


@router.post(
    "/{patient_id}/deactivate",
    response_model=PatientRead,
    summary="Soft-deactivate a patient (records are never hard-deleted)",
    responses={404: {"model": ErrorResponse}, 409: {"model": ErrorResponse}},
)
def deactivate_patient(patient_id: uuid.UUID, db: DbSession, actor: PatientDeactivator) -> PatientRead:
    return PatientRead.model_validate(PatientService(db).deactivate_patient(patient_id, actor=actor))
